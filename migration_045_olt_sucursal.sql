-- Sirve para que el cruce con SmartOLT busque solo entre los clientes de la sucursal de esa OLT, en vez de leer toda la base.
-- Se ejecuta UNA sola vez:
--
--   npx wrangler d1 execute vnet_fallas_masivas --remote --file=./migration_045_olt_sucursal.sql

